namespace HFLabs.ML.Agentic;

using System;
using System.Collections.Generic;
using System.Threading;
using System.Threading.Tasks;

/// <summary>
/// Represents structured feedback provided by an evaluator on an agent candidate.
/// Conforms to PAT-CS-246.
/// </summary>
public sealed record ReflectionFeedback(
    bool Passed,
    double Score,
    string Critique,
    IReadOnlyList<string> ActionableSuggestions);

/// <summary>
/// Records a single iteration entry in the reflection trajectory.
/// Conforms to PAT-CS-246.
/// </summary>
public sealed record ReflectionHistoryEntry<TCandidate>(
    int Cycle,
    TCandidate Candidate,
    ReflectionFeedback Feedback,
    TimeSpan Duration);

/// <summary>
/// Contract for evaluating a candidate generated by an optimizer agent.
/// </summary>
public interface IReflectionEvaluator<in TCandidate>
{
    Task<ReflectionFeedback> EvaluateAsync(TCandidate candidate, CancellationToken cancellationToken = default);
}

/// <summary>
/// Contract for generating or refining candidate solutions based on task context and prior feedback.
/// </summary>
public interface IReflectionOptimizer<in TContext, TCandidate>
{
    Task<TCandidate> GenerateOrRefineAsync(
        TContext context,
        TCandidate? previousCandidate,
        ReflectionFeedback? previousFeedback,
        CancellationToken cancellationToken = default);
}

/// <summary>
/// Orchestrates an Evaluator-Optimizer reflection loop with bounded budgets and convergence checks.
/// Conforms to PAT-CS-246.
/// </summary>
public sealed class ReflectionLoop<TContext, TCandidate>(
    IReflectionOptimizer<TContext, TCandidate> optimizer,
    IReflectionEvaluator<TCandidate> evaluator,
    int maxCycles = 3,
    double passingScore = 0.85)
{
    public int MaxCycles { get; } = Math.Max(1, maxCycles);
    public double PassingScore { get; } = passingScore;

    public async Task<(TCandidate BestCandidate, IReadOnlyList<ReflectionHistoryEntry<TCandidate>> History)> ExecuteAsync(
        TContext context,
        CancellationToken cancellationToken = default)
    {
        List<ReflectionHistoryEntry<TCandidate>> history = [];
        TCandidate? current = default;
        ReflectionFeedback? feedback = null;
        TCandidate? best = default;
        double highestScore = double.MinValue;

        for (int cycle = 1; cycle <= MaxCycles; cycle++)
        {
            cancellationToken.ThrowIfCancellationRequested();
            DateTime start = DateTime.UtcNow;

            current = await optimizer.GenerateOrRefineAsync(context, current, feedback, cancellationToken).ConfigureAwait(false);
            feedback = await evaluator.EvaluateAsync(current, cancellationToken).ConfigureAwait(false);

            history.Add(new ReflectionHistoryEntry<TCandidate>(cycle, current, feedback, DateTime.UtcNow - start));

            if (feedback.Score > highestScore)
            {
                highestScore = feedback.Score;
                best = current;
            }

            if (feedback.Passed && feedback.Score >= PassingScore)
            {
                break;
            }
        }

        return (best ?? current!, history);
    }
}
